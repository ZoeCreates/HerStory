    /// kinds 默认从存储里读，所以 widget 和推送不用改调用就会跟着用户的分类走
    static func today(_ date: Date = .now, topics: Set<Topic> = [], kinds: Set<QuoteKind> = QuoteKind.saved) -> Quote {
        // ① 先按分类筛（没选 = 全部；万一筛完是空的，也退回全部）
        let ofKind = all.filter { kinds.isEmpty || kinds.contains($0.kind) }
        let base = ofKind.isEmpty ? all : ofKind
        // ② 再按 topic 筛
        let matching = base.filter { !topics.isDisjoint(with: $0.topics) }
        let pool = matching.isEmpty ? base : matching
        let day = Calendar.current.ordinality(of: .day, in: .era, for: date) ?? 0
        return pool[day % pool.count]
    }
    
